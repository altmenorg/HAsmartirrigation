"""Write the program YAML reference tables of the docs from config_reference.

The tables in docs/usage-full-controller.md, between the two markers below,
are generated from ``custom_components/smart_irrigation/config_reference.py``,
the reference assistants read (GetConfigReference). One source, so the docs and
the assistants never disagree about a key, its range or its default.

    py scripts/gen_yaml_reference.py          # rewrite the tables
    py scripts/gen_yaml_reference.py --check  # fail if they are out of date
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from custom_components.smart_irrigation import config_reference as ref  # noqa: E402

DOC = ROOT / "docs" / "usage-full-controller.md"
START = "<!-- yaml-reference:start (generated by scripts/gen_yaml_reference.py) -->"
END = "<!-- yaml-reference:end -->"

# Keys a program is written without: an id is made from the name, and the
# old program-wide delay is only read from old stores.
SKIP = {"program": {"id", "delay"}, "step": {"id"}, "schedule": {"id"}}


def _range(f: dict) -> str:
    if "values" in f:
        return ", ".join(f"`{v}`" for v in f["values"])
    if "min" in f and "max" in f:
        unit = f" {f['unit']}" if f.get("unit") else ""
        lo, hi = f["min"], f["max"]
        lo = int(lo) if float(lo).is_integer() else lo
        hi = int(hi) if float(hi).is_integer() else hi
        return f"{lo} to {hi}{unit}"
    return f["type"]


def _default(f: dict) -> str:
    if "default" not in f:
        return ""
    d = f["default"]
    if isinstance(d, bool):
        return f"`{str(d).lower()}`"
    if isinstance(d, float) and d.is_integer():
        d = int(d)
    return f"`{d}`"


def _table(fields: dict, skip: set, types: bool = False) -> str:
    head = "| Key | Values | Default | What it does |\n| --- | --- | --- | --- |\n"
    rows = []
    for key, f in fields.items():
        if key in skip:
            continue
        meaning = f.get("meaning", "").replace("|", "\\|")
        if types and f.get("schedule_types"):
            meaning += f" *({', '.join(f['schedule_types'])} only)*"
        if f.get("yaml_only"):
            meaning = "**YAML only.** " + meaning
        elif f.get("advanced"):
            meaning = "**Advanced mode.** " + meaning
        rows.append(f"| `{key}` | {_range(f)} | {_default(f)} | {meaning} |")
    return head + "\n".join(rows) + "\n"


def render() -> str:
    return (
        f"{START}\n\n"
        "#### Program\n\n" + _table(ref.PROGRAM_FIELDS, SKIP["program"]) + "\n"
        "#### Step\n\n" + _table(ref.STEP_FIELDS, SKIP["step"]) + "\n"
        "#### Schedule\n\n" + _table(ref.SCHEDULE_FIELDS, SKIP["schedule"], True) + "\n"
        "#### Notify\n\n" + _table(ref.NOTIFY_FIELDS, set()) + "\n"
        f"{END}"
    )


def main() -> int:
    text = DOC.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"{DOC.name}: markers not found")
        return 1
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    new = before + render() + after
    if "--check" in sys.argv:
        if new != text:
            print(
                f"{DOC.name}: the YAML reference is out of date; run {Path(__file__).name}"
            )
            return 1
        return 0
    DOC.write_text(new, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
